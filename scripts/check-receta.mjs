import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createServer } from 'vite';
const server = await createServer({ server: { middlewareMode: true, ws: false }, appType: 'custom' });
const originalFetch = globalThis.fetch;
try {
  globalThis.fetch = async path => new Response(await readFile(new URL(`../public${path}`, import.meta.url)));
  const { buildRecetaPdf } = await server.ssrLoadModule('/src/lib/recetaPdf.js');
  const { RECETA_CATALOGO, normalizarBusqueda, buscarMedicamentos, FRECUENCIAS_RECETA, opcionesDosis, textoMedicamento, precargaPresentacion, actualizarPresentacion } = await server.ssrLoadModule('/src/lib/recetaCatalogo.js');
  assert.ok(RECETA_CATALOGO.length > 150);
  assert.equal(new Set(RECETA_CATALOGO.map(m => m.nombre)).size, RECETA_CATALOGO.length);
  assert.equal(normalizarBusqueda('Ácido'), 'acido');
  const losartan = buscarMedicamentos('LOSARTAN 100')[0];
  assert.equal(losartan.nombre, 'Losartán');
  assert.deepEqual(losartan.presentaciones, ['50 mg · comprimido', '100 mg · comprimido']);
  assert.ok(buscarMedicamentos('metformina 750').some(m => m.nombre === 'Metformina liberación prolongada'));
  assert.deepEqual(buscarMedicamentos('medicamento inexistente'), []);
  assert.ok(FRECUENCIAS_RECETA.includes('Cada 72 horas'));
  assert.ok(opcionesDosis('50 mg · comprimido').includes('1 comprimido'));
  assert.ok(!opcionesDosis('750 mg · comprimido de liberación prolongada').some(d => d.includes('½')));
  assert.ok(opcionesDosis('100 mg/5 mL · suspensión oral').includes('5 mL'));
  for (const item of RECETA_CATALOGO) assert.equal(new Set(item.presentaciones).size, item.presentaciones.length);
  assert.equal(textoMedicamento({nombre: 'Losartán', presentacion: losartan.presentaciones[1], frecuencia: 'Cada 24 horas', duracion: '30 días'}), 'Losartán · 100 mg · comprimido · Frecuencia: Cada 24 horas · Duración: 30 días');
  assert.deepEqual(precargaPresentacion('50 mg · comprimido'), { dosis: '1 comprimido', via: 'Oral' });
  assert.deepEqual(precargaPresentacion('20 mg · cápsula gastrorresistente'), { dosis: '1 cápsula', via: 'Oral' });
  assert.deepEqual(precargaPresentacion('500 mg · cápsula vaginal'), { dosis: '', via: '' });
  assert.deepEqual(precargaPresentacion('2 % · solución inyectable'), { dosis: '', via: '' });
  const previo = { presentacion: '50 mg · comprimido', dosis: '1 comprimido', via: 'Oral' };
  assert.equal(actualizarPresentacion(previo, '20 mg · cápsula').dosis, '1 cápsula');
  assert.equal(actualizarPresentacion({ ...previo, dosis: '2 comprimidos' }, '100 mg · comprimido').dosis, '2 comprimidos');
  assert.equal(actualizarPresentacion(previo, '').via, '');
  const receta = { paciente: 'Paciente de prueba', rut: '12.345.678-5', edad: '40', direccion: 'Calle de prueba 123', fecha: '2026-10-20', diagnostico: 'Control', observaciones: '', institucion: 'inalab', firma: false, medicamentos: [{ nombre: 'Losartán', presentacion: '100 mg · comprimido', dosis: '1 comprimido', via: 'oral', frecuencia: 'cada 24 horas', duracion: '30 días' }] };
  const sinFirma = await buildRecetaPdf(receta);
  assert.equal(sinFirma.getNumberOfPages(), 1);
  assert.ok(sinFirma.output().includes('100 mg'));
  assert.ok(sinFirma.output().includes('cada 24 horas'));
  assert.ok(!sinFirma.output().includes('Firma electr'));
  const conFirma = await buildRecetaPdf({ ...receta, firma: true });
  assert.ok(conFirma.output().includes('Firma electr'));
  assert.ok(conFirma.output('arraybuffer').byteLength > sinFirma.output('arraybuffer').byteLength);
  const larga = await buildRecetaPdf({ ...receta, medicamentos: Array.from({ length: 60 }, (_, i) => ({ ...receta.medicamentos[0], nombre: `Medicamento ${i + 1}`, indicaciones: 'Texto largo de instrucciones. '.repeat(12) })) });
  assert.ok(larga.getNumberOfPages() > 2);
  assert.ok(larga.output().includes('Medicamento 60'));
  assert.ok(larga.output().includes(`de ${larga.getNumberOfPages()}`));
  await buildRecetaPdf({ ...receta, institucion: 'bulnes', firma: true });
  globalThis.fetch = async () => new Response('', { status: 404 });
  await assert.rejects(buildRecetaPdf({ ...receta, firma: true }), /imagen/);
  console.log(`OK: ${RECETA_CATALOGO.length} medicamentos, PDF con/sin firma, ambas instituciones, error de imagen y receta de ${larga.getNumberOfPages()} páginas.`);
} finally {
  globalThis.fetch = originalFetch;
  await server.close();
}
