import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createServer } from 'vite';
const server = await createServer({ server: { middlewareMode: true, ws: false }, appType: 'custom' });
const originalFetch = globalThis.fetch;
try {
  globalThis.fetch = async path => new Response(await readFile(new URL(`../public${path}`, import.meta.url)));
  const { buildRecetaPdf } = await server.ssrLoadModule('/src/lib/recetaPdf.js');
  const { RECETA_CATALOGO, normalizarBusqueda, buscarMedicamentos, FRECUENCIAS_RECETA, opcionesDosis, textoMedicamento, precargaPresentacion, actualizarPresentacion } = await server.ssrLoadModule('/src/lib/recetaCatalogo.js');
  assert.ok(RECETA_CATALOGO.length >= 216);
  const { precargaMedicamento, frecuenciasMedicamento } = await server.ssrLoadModule('/src/lib/recetaCatalogo.js');
  const mtx = buscarMedicamentos('metotrexato 2.5')[0];
  assert.equal(mtx.nombre, 'Metotrexato');
  assert.ok(mtx.presentaciones.includes('2,5 mg · comprimido'));
  assert.ok(buscarMedicamentos('Metoject 15').some(m => m.nombre === 'Metotrexato'));
  assert.deepEqual(precargaMedicamento('Metotrexato', '2,5 mg · comprimido'), { dosis: '', via: 'Oral' });
  assert.deepEqual(precargaMedicamento('Metotrexato', '15 mg/0,3 mL · solución inyectable'), { dosis: '', via: '' });
  assert.equal(actualizarPresentacion({ nombre: 'Metotrexato', dosis: '', via: '', presentacion: '' }, '2,5 mg · comprimido').dosis, '');
  assert.ok(frecuenciasMedicamento('Metotrexato').includes('Una vez por semana (lunes)'));
  assert.ok(!frecuenciasMedicamento('Metotrexato').includes('Cada 24 horas'));
  for (const nombre of ['Metotrexato', 'Hidroxicloroquina', 'Leflunomida', 'Azatioprina', 'Sulfasalazina', 'Micofenolato mofetilo', 'Micofenolato sódico', 'Tacrolimus', 'Apixabán', 'Rivaroxabán', 'Dabigatrán etexilato', 'Warfarina', 'Acenocumarol']) {
    assert.ok(RECETA_CATALOGO.find(m => m.nombre === nombre)?.presentaciones.length > 0, nombre);
  }
  const { calcularComprimidos, cantidadControlada, numeroEnLetras, esBenzodiacepina } = await server.ssrLoadModule('/src/lib/recetaControlados.js');
  const { nuevaMagistral, MAGISTRALES } = await server.ssrLoadModule('/src/lib/recetaMagistrales.js');
  const benzo = { nombre: 'Clonazepam', presentacion: '2 mg · comprimido', dosis: '½ comprimido', via: 'Oral', frecuencia: 'Cada 12 horas', duracion: '30 días' };
  assert.equal(calcularComprimidos(benzo), 30);
  assert.equal(cantidadControlada(benzo), '30 (treinta) comprimidos');
  assert.equal(calcularComprimidos({ ...benzo, dosis: '1/4 comprimido', duracion: '7 días', frecuencia: 'Cada 24 horas' }), 2);
  assert.equal(calcularComprimidos({ ...benzo, dosis: '1 comprimido', duracion: '1 semana', frecuencia: 'Cada 48 horas' }), 4);
  for (const cambios of [{ dosis: '0 comprimidos' }, { dosis: '1 a 2 comprimidos' }, { frecuencia: 'Cada 0 horas' }, { frecuencia: 'SOS' }, { duracion: 'Uso permanente' }, { duracion: '0 días' }, { indicaciones: 'Reducir dosis semanalmente' }, { presentacion: '2 mg/mL · gotas' }]) assert.equal(calcularComprimidos({ ...benzo, ...cambios }), null);
  assert.equal(cantidadControlada({ ...benzo, frecuencia: 'SOS', cantidadManual: '15' }), '15 (quince) comprimidos');
  assert.equal(cantidadControlada({ ...benzo, frecuencia: 'SOS', cantidadManual: '-1' }), '');
  assert.equal(cantidadControlada({ ...benzo, dosis: '2 comprimidos', cantidadManual: '15' }), '120 (ciento veinte) comprimidos');
  assert.equal(cantidadControlada({ ...benzo, presentacion: '2 mg/mL · gotas', cantidadManual: '1', unidadCantidad: 'frascos' }), '1 (uno) frascos');
  assert.equal(cantidadControlada({ ...benzo, presentacion: '2 mg/mL · gotas', cantidadManual: '1' }), '');
  assert.equal(numeroEnLetras(21), 'veintiuno');
  assert.equal(numeroEnLetras(100), 'cien');
  assert.equal(numeroEnLetras(1001), 'mil uno');
  assert.ok(esBenzodiacepina({ nombre: 'Ravotril 2 mg' }));
  assert.ok(esBenzodiacepina({ nombre: 'Neuroval CD' }));
  assert.ok(!esBenzodiacepina({ nombre: 'Paracetamol' }));
  assert.ok(buscarMedicamentos('ravotril 2').some(m => m.nombre === 'Clonazepam'));
  assert.ok(buscarMedicamentos('adax 0.5').some(m => m.nombre === 'Alprazolam'));
  assert.ok(buscarMedicamentos('cozaar 50').some(m => m.nombre === 'Losartán'));
  assert.ok(buscarMedicamentos('', 'Benzodiacepinas').every(esBenzodiacepina));
  assert.equal(new Set(RECETA_CATALOGO.map(m => m.nombre)).size, RECETA_CATALOGO.length);
  assert.equal(normalizarBusqueda('Ácido'), 'acido');
  const losartan = buscarMedicamentos('LOSARTAN 100')[0];
  assert.equal(losartan.nombre, 'Losartán');
  assert.deepEqual(losartan.presentaciones, ['50 mg · comprimido', '100 mg · comprimido']);
  assert.ok(buscarMedicamentos('metformina 750').some(m => m.nombre === 'Metformina liberación prolongada'));
  assert.deepEqual(buscarMedicamentos('medicamento inexistente'), []);
  assert.ok(FRECUENCIAS_RECETA.includes('Cada 72 horas'));
  assert.ok(opcionesDosis('50 mg · comprimido').includes('1 comprimido'));
  assert.ok(!opcionesDosis('750 mg · comprimido de liberación prolongada').some(d => d.includes('½')));
  assert.ok(opcionesDosis('100 mg/5 mL · suspensión oral').includes('5 mL'));
  for (const item of RECETA_CATALOGO) assert.equal(new Set(item.presentaciones).size, item.presentaciones.length);
  assert.equal(textoMedicamento({nombre: 'Losartán', presentacion: losartan.presentaciones[1], frecuencia: 'Cada 24 horas', duracion: '30 días'}), 'Losartán\nPresentación: 100 mg · comprimido\nFrecuencia: Cada 24 horas\nDuración: 30 días');
  assert.deepEqual(precargaPresentacion('50 mg · comprimido'), { dosis: '1 comprimido', via: 'Oral' });
  assert.deepEqual(precargaPresentacion('20 mg · cápsula gastrorresistente'), { dosis: '1 cápsula', via: 'Oral' });
  assert.deepEqual(precargaPresentacion('500 mg · cápsula vaginal'), { dosis: '', via: '' });
  assert.deepEqual(precargaPresentacion('2 % · solución inyectable'), { dosis: '', via: '' });
  const previo = { presentacion: '50 mg · comprimido', dosis: '1 comprimido', via: 'Oral' };
  assert.equal(actualizarPresentacion(previo, '20 mg · cápsula').dosis, '1 cápsula');
  assert.equal(actualizarPresentacion({ ...previo, dosis: '2 comprimidos' }, '100 mg · comprimido').dosis, '2 comprimidos');
  assert.equal(actualizarPresentacion(previo, '').via, '');
  const receta = { paciente: 'Paciente de prueba', rut: '12.345.678-5', edad: '40', direccion: 'Calle de prueba 123', fecha: '2026-10-20', diagnostico: 'Control', observaciones: '', institucion: 'inalab', firma: false, medicamentos: [{ nombre: 'Losartán', presentacion: '100 mg · comprimido', dosis: '1 comprimido', via: 'oral', frecuencia: 'cada 24 horas', duracion: '30 días' }] };
  assert.throws(() => buildRecetaPdf({ ...receta, direccion: '', medicamentos: [benzo] }), /dirección/);
  assert.throws(() => buildRecetaPdf({ ...receta, medicamentos: [{ ...benzo, duracion: 'Uso permanente' }] }), /cantidad total/);
  const recetaMtx = { ...receta, medicamentos: [{ nombre: 'Metotrexato', presentacion: mtx.presentaciones[0], dosis: 'Dosis de prueba', via: 'Oral', frecuencia: 'Una vez por semana (lunes)', duracion: '4 semanas' }] };
  const pdfMtx = await buildRecetaPdf(recetaMtx);
  assert.ok(pdfMtx.output().includes('Metotrexato'));
  assert.ok(pdfMtx.output().includes('2,5 mg'));
  assert.ok(pdfMtx.output().includes('Una vez por semana'));
  assert.ok(pdfMtx.output().includes('lunes'));
  const pdfBenzo = await buildRecetaPdf({ ...receta, medicamentos: [benzo] });
  assert.ok(pdfBenzo.output().includes('treinta'));
  assert.ok(textoMedicamento(benzo).includes('30 (treinta) comprimidos'));
  const magistral = { ...nuevaMagistral(MAGISTRALES[0]), vehiculo: 'Base crema c.s.p. 30 g', cantidad: '30 g', dosis: 'Según indicación médica', frecuencia: 'Según pauta', duracion: 'Según pauta' };
  assert.throws(() => buildRecetaPdf({ ...receta, medicamentos: [{ ...magistral, vehiculo: '' }] }), /vehículo/);
  const pdfMagistral = await buildRecetaPdf({ ...receta, medicamentos: [magistral] });
  assert.ok(pdfMagistral.output().includes('Diltiazem'));
  assert.ok(pdfMagistral.output().includes('Base crema'));
  const { buildDocumentoClinicoPdf } = await server.ssrLoadModule('/src/lib/recetaPdf.js');
  const derivacion = await buildDocumentoClinicoPdf({ ...receta, textoLibre: 'Solicito evaluación. 12 sesiones.' }, { titulo: 'DERIVACIÓN A OTROS PROFESIONALES', seccion: 'Profesional de destino: Nutricionista' });
  assert.ok(derivacion.output().includes('Nutricionista'));
  assert.ok(derivacion.output().includes('12 sesiones'));
  const libre = await buildRecetaPdf({ ...receta, medicamentos: [], textoLibre: 'Orden de kinesioterapia. 12 sesiones.' });
  assert.ok(libre.output().includes('12 sesiones'));
  assert.equal(libre.getNumberOfPages(), 1);
  const medicoEditado = { nombre: 'Profesional de prueba', rut: '12.345.678-5', titulo: 'Medicina general' };
  const pdfMedico = await buildRecetaPdf({ ...receta, medico: medicoEditado, firma: true });
  assert.ok(pdfMedico.output().includes('Profesional de prueba'));
  assert.ok(pdfMedico.output().includes('Medicina general'));
  assert.ok(!pdfMedico.output().includes('Fernando Alvarado'));
  assert.ok(!pdfMedico.output().includes('Firma electr'));
  await assert.rejects(buildRecetaPdf({ ...receta, medico: { ...medicoEditado, rut: '123' } }), /médico/);
  const sinFirma = await buildRecetaPdf(receta);
  assert.equal(sinFirma.getNumberOfPages(), 1);
  assert.ok(sinFirma.output().includes('100 mg'));
  assert.ok(sinFirma.output().includes('cada 24 horas'));
  assert.ok(!sinFirma.output().includes('Firma electr'));
  const conFirma = await buildRecetaPdf({ ...receta, firma: true });
  assert.ok(conFirma.output().includes('Firma electr'));
  assert.ok(conFirma.output('arraybuffer').byteLength > sinFirma.output('arraybuffer').byteLength);
  const larga = await buildRecetaPdf({ ...receta, medicamentos: Array.from({ length: 60 }, (_, i) => ({ ...receta.medicamentos[0], nombre: `Medicamento ${i + 1}`, indicaciones: 'Texto largo de instrucciones. '.repeat(12) })) });
  assert.ok(larga.getNumberOfPages() > 2);
  assert.ok(larga.output().includes('Medicamento 60'));
  assert.ok(larga.output().includes(`de ${larga.getNumberOfPages()}`));
  await buildRecetaPdf({ ...receta, institucion: 'bulnes', firma: true });
  globalThis.fetch = async () => new Response('', { status: 404 });
  await assert.rejects(buildRecetaPdf({ ...receta, firma: true }), /imagen/);
  console.log(`OK: ${RECETA_CATALOGO.length} medicamentos, PDF con/sin firma, ambas instituciones, error de imagen y receta de ${larga.getNumberOfPages()} páginas.`);
} finally {
  globalThis.fetch = originalFetch;
  await server.close();
}
